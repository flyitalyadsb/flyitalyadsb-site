function overflightsSkillMd(): string {
  return [
    '# Aircraft that flew over a place',
    '',
    'List the aircraft whose recorded track passed within a radius of a place during a past time',
    'window, via the `overflights` MCP tool: "what flew over my house this morning?", "which',
    'helicopters passed over this town yesterday afternoon?". It is about aircraft, never people:',
    'nothing in the answer says who was on board.',
    '',
    '## Requirements',
    '',
    `- Connect to the MCP server at \`${MCP_URL}\` (Streamable HTTP, stateless).`,
    '- Every request needs an `X-Api-Key` header (or the OAuth connection) — the same key issued for',
    '  `api.flyitalyadsb.com/v2/*`. Each call counts as one request.',
    '- The place: `lat` and `lon`, or `airport` (one of FlyItalyADSB\'s curated Italian airports), or',
    '  nothing to use the position saved on the account (see the `my-location` skill).',
    '- The window: `lastHours` (default 3), or `from` and optional `to` in ISO 8601 (UTC when no offset).',
    '- `radiusKm` (default 3) and the window have a maximum that depends on the plan: 10 km and 6 h on',
    '  Free, 25 km and 24 h on Starter, 50 km and 24 h above. Over it, the tool returns the API\'s',
    '  error with a link to the answer.',
    '- Optional `maxAltFt` (only the part of each track at or below that altitude) and `limit` (default',
    '  50, max 200).',
    '- Coverage: every day since 2026-08-17. Today lags by up to ~15 minutes; for right now use',
    '  `aircraft_near`.',
    '',
    '## Read the answer',
    '',
    '- `overflights`: one entry per aircraft, sorted by `closest_time` (UTC): `icao`, `r`',
    '  (registration), `t` (type), `callsigns`, `closest_km`, `closest_alt_ft` and `min_alt_ft` (feet,',
    '  or `"ground"`), `entered`/`left`, `passes`, `source` and `sources` (`adsb`, `mlat`, `tisb`,',
    '  `other`), `positions` (received positions inside the circle: 0 means the pass is a straight',
    '  line between positions just outside it), `dbFlags`, and `history` (the API paths of the',
    '  day\'s full track; `aircraft_history` with the same icao and date fetches it).',
    '- `coverage.gaps`: periods that were NOT searched (not indexed yet, or not covered). Never',
    '  conclude that nothing flew over in them. `notes` repeats them in plain words.',
    '- `truncated` with `completeUntil`: every pass before that time is listed; call again with',
    '  `from` = `completeUntil` for the rest.',
    '- ADS-B positions can be wrong or spoofed, and MLAT is less precise: quote the source when',
    '  it matters.',
    '',
    '## Validate',
    '',
    '```',
    `POST ${MCP_URL}`,
    'Content-Type: application/json',
    'X-Api-Key: <your-key>',
    '',
    '{"jsonrpc":"2.0","id":1,"method":"tools/call","params":{"name":"overflights","arguments":{"airport":"LIN","radiusKm":3,"lastHours":2}}}',
    '```',
    '',
    'Check that `result.content[0].text` parses as JSON with `center`, `count`, `coverage`',
    '(`{complete, gaps}`), `truncated` and an `overflights` array.',
    '',
  ].join('\n');
}

